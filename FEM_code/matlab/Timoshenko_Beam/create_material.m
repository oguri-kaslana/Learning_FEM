function C = create_material(E, I, kappa_s, G, A)
% ============================================================
% create_material
%
% 功能：
%   构造 Timoshenko 梁单元的材料刚度矩阵。
%
% 输出：
%   C = [E*I,      0;
%        0,   kappa_s*G*A]
% ============================================================

    % ========================================================
    % 与 Euler 梁不同：
    % Euler 梁只有弯曲刚度 EI；
    % Timoshenko 梁同时包含弯曲刚度 EI 和剪切刚度 kappa_s*G*A。
    % ========================================================
    C = [
        E * I,             0;
        0,       kappa_s * G * A
    ];

end
